-- =====================================================================
-- Etapa 3, migración 2: "Me sirvió" y Reportar en las experiencias de finales (F21)
-- Correr en la BASE DE PRUEBA, después de la migración 1. Idempotente y en
-- una transacción. Vuelta atrás: supabase/rollback/20261108010000_finales_votos_reportes.sql
--
-- Qué hace:
--  1. Columna votos_utilidad en experiencias_finales (empieza en 0) y la suma
--     a la vista pública.
--  2. Tabla votos_finales: un voto por persona y experiencia. Solo la mueve
--     la función votar_final (igual que los votos de reseñas).
--  3. Tabla reportes_finales: un reporte por persona y experiencia, con el
--     motivo. Se escribe solo desde el servidor; la lee el panel de admin.
-- El tipo del id de experiencias_finales se toma de la base (uuid o número).
-- No borra ni cambia filas existentes.
-- =====================================================================

BEGIN;

ALTER TABLE public.experiencias_finales
  ADD COLUMN IF NOT EXISTS votos_utilidad integer NOT NULL DEFAULT 0;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'finales_votos_no_negativos') THEN
    ALTER TABLE public.experiencias_finales ADD CONSTRAINT finales_votos_no_negativos
      CHECK (votos_utilidad >= 0) NOT VALID;
  END IF;
END $$;

-- La vista suma la columna al final (CREATE OR REPLACE solo deja agregar al final)
CREATE OR REPLACE VIEW public.experiencias_finales_publicas AS
SELECT
  f.id,
  f.materia_id,
  f.anio,
  f.mesa,
  f.profesor_nombre,
  f.comentario,
  f.es_anonima,
  CASE WHEN f.es_anonima THEN NULL ELSE f.nombre_usuario END AS nombre_usuario,
  f.created_at,
  f.votos_utilidad
FROM public.experiencias_finales f;

GRANT SELECT ON public.experiencias_finales_publicas TO anon, authenticated;

DO $do$
DECLARE
  tipo text;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod) INTO tipo
  FROM pg_attribute a
  WHERE a.attrelid = 'public.experiencias_finales'::regclass AND a.attname = 'id';

  EXECUTE format($f$
    CREATE TABLE IF NOT EXISTS public.votos_finales (
      user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
      final_id %1$s NOT NULL REFERENCES public.experiencias_finales(id) ON DELETE CASCADE,
      created_at timestamptz NOT NULL DEFAULT now(),
      PRIMARY KEY (user_id, final_id)
    )$f$, tipo);

  EXECUTE format($f$
    CREATE TABLE IF NOT EXISTS public.reportes_finales (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      final_id %1$s NOT NULL REFERENCES public.experiencias_finales(id) ON DELETE CASCADE,
      user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
      motivo text NOT NULL CHECK (char_length(motivo) BETWEEN 3 AND 500),
      created_at timestamptz NOT NULL DEFAULT now(),
      UNIQUE (final_id, user_id)
    )$f$, tipo);

  -- Votar: suma o resta de a uno, una sola vez por persona.
  EXECUTE format($f$
    CREATE OR REPLACE FUNCTION public.votar_final(p_final_id %1$s, p_votar boolean)
    RETURNS integer
    LANGUAGE plpgsql
    SECURITY DEFINER
    SET search_path = public
    AS $fn$
    DECLARE
      v_uid uuid := auth.uid();
      v_rows int;
      v_votos int;
    BEGIN
      IF v_uid IS NULL THEN
        RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000';
      END IF;
      IF p_votar THEN
        INSERT INTO votos_finales (user_id, final_id) VALUES (v_uid, p_final_id) ON CONFLICT DO NOTHING;
        GET DIAGNOSTICS v_rows = ROW_COUNT;
        IF v_rows > 0 THEN
          UPDATE experiencias_finales SET votos_utilidad = votos_utilidad + 1 WHERE id = p_final_id;
        END IF;
      ELSE
        DELETE FROM votos_finales WHERE user_id = v_uid AND final_id = p_final_id;
        GET DIAGNOSTICS v_rows = ROW_COUNT;
        IF v_rows > 0 THEN
          UPDATE experiencias_finales SET votos_utilidad = GREATEST(votos_utilidad - 1, 0) WHERE id = p_final_id;
        END IF;
      END IF;
      SELECT votos_utilidad INTO v_votos FROM experiencias_finales WHERE id = p_final_id;
      RETURN COALESCE(v_votos, 0);
    END;
    $fn$$f$, tipo);

  EXECUTE format('REVOKE ALL ON FUNCTION public.votar_final(%1$s, boolean) FROM PUBLIC, anon', tipo);
  EXECUTE format('GRANT EXECUTE ON FUNCTION public.votar_final(%1$s, boolean) TO authenticated', tipo);
END $do$;

-- Votos: cada uno ve los suyos (para pintar el botón); escribir, solo la función.
ALTER TABLE public.votos_finales ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Votos de finales: cada uno lee los suyos" ON public.votos_finales;
CREATE POLICY "Votos de finales: cada uno lee los suyos" ON public.votos_finales
  FOR SELECT USING (auth.uid() = user_id);
REVOKE INSERT, UPDATE, DELETE ON public.votos_finales FROM anon, authenticated;

-- Reportes: sin acceso con las claves públicas; los maneja el servidor.
ALTER TABLE public.reportes_finales ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.reportes_finales FROM anon, authenticated;

COMMIT;

-- Verificación: tiene que decir tablas = 2, funcion = 1, columna = 1.
SELECT
  (SELECT count(*) FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name IN ('votos_finales', 'reportes_finales')) AS tablas,
  (SELECT count(*) FROM pg_proc WHERE proname = 'votar_final') AS funcion,
  (SELECT count(*) FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'experiencias_finales_publicas' AND column_name = 'votos_utilidad') AS columna;
